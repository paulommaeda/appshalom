const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium, request} = require(process.env.IGREJA_PLAYWRIGHT);
const base = 'http://127.0.0.1:8080';
let checks = 0;
function check(value, message) {assert.ok(value, message);checks++;}
(async () => {
  const browser = await chromium.launch({headless:true});
  const http = await request.newContext();
  try {
    const context = await browser.newContext({viewport:{width:390,height:844}});
    const page = await context.newPage();
    await page.goto(base + '/wp-login.php?redirect_to=' + encodeURIComponent(base + '/wp-admin/admin.php?page=igreja-erp-transfer'));
    await page.locator('#user_login').fill('tests');
    await page.locator('#user_pass').fill('igreja_erp_disposable_test');
    await Promise.all([page.waitForURL(u=>!u.pathname.endsWith('/wp-login.php')),page.locator('#wp-submit').click()]);
    check(await page.getByRole('heading',{name:'Importar / exportar dados',exact:true}).count() === 1,'Área no Core');
    check((await http.post(base+'/wp-admin/admin-post.php',{form:{action:'igreja_erp_transfer_export',type:'settings'}})).status()===401,'Exportação não é pública');
    const rejected = await context.request.post(base+'/wp-admin/admin-post.php',{form:{action:'igreja_erp_transfer_export',type:'settings',_wpnonce:'invalid'}});
    check(rejected.status()===403,'Exportação exige nonce');
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:'Exportar Configurações',exact:true}).click();
    const download=await downloadPromise;
    check(download.suggestedFilename().endsWith('.json'),'Exporta JSON de configurações');
    const settings=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    check(settings.format==='appshalom' && !JSON.stringify(settings).includes('fixture-secret'),'Exportação não expõe segredo');
    settings.data.igreja.nome_curto='Igreja Importada no Navegador';
    await page.locator('input[type=file][accept=".json"]').setInputFiles({name:'config.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(settings))});
    const settingsForm=page.locator('form').filter({has:page.locator('input[type=file][accept=".json"]')});
    await Promise.all([page.waitForNavigation(),settingsForm.getByRole('button',{name:'Conferir importação'}).click()]);
    check(await page.getByRole('heading',{name:'Prévia da importação'}).count()===1,'Prévia de configurações');
    await Promise.all([page.waitForNavigation(),page.getByRole('button',{name:'Confirmar importação'}).click()]);
    await page.goto(base+'/wp-admin/admin.php?page=igreja-erp-core');
    check(await page.getByLabel('Nome de apresentação',{exact:true}).inputValue()==='Igreja Importada no Navegador','Configuração aplicada');
    await page.goto(base+'/wp-admin/admin.php?page=igreja-erp-transfer');
    const csv='nome_completo;email;familia;parentesco\nMarina Beatriz Testeconvidado;marina-browser@example.org;Família Convite;Titular\n';
    await page.locator('input[type=file][accept=".csv"]').setInputFiles({name:'membros.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
    const memberForm=page.locator('form').filter({has:page.locator('input[type=file][accept=".csv"]')});
    await Promise.all([page.waitForNavigation(),memberForm.getByRole('button',{name:'Conferir importação'}).click()]);
    check((await page.locator('body').textContent()).includes('novo(s) pendente(s)'),'Importação informa pendência de aprovação');
    await Promise.all([page.waitForNavigation(),page.getByRole('button',{name:'Confirmar importação'}).click()]);
    await page.goto(base+'/wp-admin/admin.php?page=igreja-erp-membros&busca=marina-browser');
    check((await page.locator('tbody').textContent()).includes('Pendente'),'Importado aguarda aprovação');
    await page.locator('tbody').getByRole('link',{name:'Editar',exact:true}).click();
    await Promise.all([page.waitForNavigation(),page.getByRole('button',{name:'Aprovar e enviar convite',exact:true}).click()]);
    check((await page.locator('body').textContent()).includes('convite enviado'),'Aprovação envia convite');
    await page.goto(base+'/wp-admin/admin.php?page=igreja-erp-membros&busca=marina-browser');
    check((await page.locator('tbody').textContent()).includes('Aprovado'),'Aprovação registrada');
    const mail=JSON.parse(fs.readFileSync(process.env.IGREJA_INVITE_FILE,'utf8'));
    check(mail.message.includes('Igreja Importada no Navegador') && mail.to==='marina-browser@example.org','Convite usa identidade importada e destinatário correto');
    const match=mail.message.match(/href="([^"]*action=rp[^"]*)"/);
    check(Boolean(match),'Convite inclui link de senha');
    const url=match[1].replaceAll('&amp;','&');
    const login=new URL(url).searchParams.get('login');
    check(login==='marina.testeconvidado','Login nome e sobrenome');
    const visitor=await browser.newContext();
    const reset=await visitor.newPage();
    await reset.goto(url);
    await reset.locator('#pass1').fill('Marina-CI-Senha-Nova-493!');
    await Promise.all([reset.waitForNavigation(),reset.locator('#wp-submit').click()]);
    await reset.goto(base+'/wp-login.php');
    await reset.locator('#user_login').fill(login);
    await reset.locator('#user_pass').fill('Marina-CI-Senha-Nova-493!');
    await Promise.all([reset.waitForURL(u=>!u.pathname.endsWith('/wp-login.php')),reset.locator('#wp-submit').click()]);
    check((await visitor.request.get(base+'/',{maxRedirects:0})).status()===200,'Convidado define senha e acessa site privado');
    await visitor.close();
    await context.close();
    console.log(checks+' verificações de importação e convite no navegador passaram.');
  } finally {await browser.close();await http.dispose();}
})().catch(error=>{console.error(error);process.exitCode=1;});
